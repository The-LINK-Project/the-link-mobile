/**
 * Brings the app's lesson recordings up to date with the website's.
 *
 *     npm run audio:sync
 *
 * Every piece of English a lesson reads aloud is a recording in the speaking
 * tutor's voice (see src/lib/lessons/audio.ts). The website records them, with
 * `npm run record:audio` in the-link-project, which listens back to each one
 * and throws away any that does not say its text. The lessons here are the
 * website's lessons, so the app ships the same files rather than recording its
 * own: one voice on both, and one place to fix a bad clip.
 *
 * This copies the recordings these lessons use into assets/lessons/audio,
 * replaces any the website has recorded again, deletes any no lesson reads any
 * more, and rewrites src/lib/lessons/audioClips.ts to list them. Commit all of
 * it afterwards. It fails, naming them, when a text has no recording on the
 * website either: record it there first, then run this again.
 *
 * The website checkout is looked for beside this repository; set LINK_WEB_DIR
 * to use another one.
 */

import {
    copyFileSync,
    existsSync,
    mkdirSync,
    readdirSync,
    readFileSync,
    rmSync,
    writeFileSync,
} from "node:fs";
import path from "node:path";

import { audioId, lessonSpokenTexts, RECORDING } from "../src/lib/lessons/audio";
import { listLessons } from "../src/lib/lessons/data";

declare global {
    // Metro defines this in the app; lookup.ts reads it to report a broken
    // lesson reference loudly in development.
    var __DEV__: boolean;
}
globalThis.__DEV__ = true;

const APP_DIR = path.resolve(__dirname, "..");
const OUT_DIR = path.join(APP_DIR, "assets/lessons/audio");
const CLIP_MAP = path.join(APP_DIR, "src/lib/lessons/audioClips.ts");
const WEB_DIR = path.resolve(
    process.env.LINK_WEB_DIR ?? path.join(APP_DIR, "../../../the-link-project"),
);
const WEB_AUDIO = path.join(WEB_DIR, "public/lessons/audio");

const clipFile = (dir: string, id: string) => path.join(dir, `${id}.mp3`);

/**
 * The website names its files after its own voice and model. If those have
 * changed, every name here misses, so say why instead of listing every text.
 */
function checkSameVoice() {
    const source = path.join(WEB_DIR, "lib/lessons/audio.ts");
    if (!existsSync(source)) return;
    const found = /RECORDING\s*=\s*\{\s*model:\s*"([^"]+)",\s*voice:\s*"([^"]+)"/.exec(
        readFileSync(source, "utf8"),
    );
    if (found && (found[1] !== RECORDING.model || found[2] !== RECORDING.voice)) {
        throw new Error(
            `The website now records with ${found[2]} on ${found[1]}, and the app with ` +
                `${RECORDING.voice} on ${RECORDING.model}. Copy RECORDING and SPOKEN_AS from ` +
                `the website's lib/lessons/audio.ts into src/lib/lessons/audio.ts, then run this again.`,
        );
    }
}

async function writeClipMap(ids: string[]) {
    const entries = ids
        .map((id) => `    "${id}": require("../../../assets/lessons/audio/${id}.mp3"),`)
        .join("\n");
    const source = `/**
 * Generated by \`npm run audio:sync\` (scripts/sync-lesson-audio.ts). Do not edit.
 *
 * Every lesson recording shipped with the app, by \`audioId\` (see audio.ts).
 * Metro only bundles a file that is required by name, so each one is listed.
 */

import type { AudioSource } from "expo-audio";

export const LESSON_CLIPS: Readonly<Record<string, AudioSource>> = {
${entries}
};
`;
    const prettier = await import("prettier");
    const options = await prettier.resolveConfig(CLIP_MAP);
    writeFileSync(CLIP_MAP, await prettier.format(source, { ...options, filepath: CLIP_MAP }));
}

async function main() {
    const haveWebsite = existsSync(WEB_AUDIO);
    if (haveWebsite) checkSameVoice();
    mkdirSync(OUT_DIR, { recursive: true });

    // Every lesson on Home. The daily mix is drawn from these, so it is covered.
    const needed = new Map<string, { text: string; lesson: string }>();
    for (const lesson of listLessons()) {
        for (const text of lessonSpokenTexts(lesson)) {
            const id = audioId(text);
            if (!needed.has(id)) needed.set(id, { text, lesson: lesson.id });
        }
    }

    const added: string[] = [];
    const updated: string[] = [];
    const missing: string[] = [];
    for (const [id, { text, lesson }] of needed) {
        const bundled = clipFile(OUT_DIR, id);
        const web = clipFile(WEB_AUDIO, id);
        if (haveWebsite && existsSync(web)) {
            if (!existsSync(bundled)) added.push(text);
            else if (!readFileSync(bundled).equals(readFileSync(web))) updated.push(text);
            else continue;
            copyFileSync(web, bundled);
        } else if (!existsSync(bundled)) {
            missing.push(`${lesson}: "${text}"`);
        }
    }

    // Anything else in the folder belongs to a text no lesson reads any more.
    const unused = readdirSync(OUT_DIR).filter(
        (file) => file.endsWith(".mp3") && !needed.has(file.slice(0, -4)),
    );
    for (const file of unused) rmSync(path.join(OUT_DIR, file));

    const shipped = [...needed.keys()].filter((id) => existsSync(clipFile(OUT_DIR, id))).sort();
    await writeClipMap(shipped);

    console.log(
        `${needed.size} texts are read aloud; ${shipped.length} have a recording in the app.` +
            (added.length ? `\n  Added ${added.length}: ${added.join(", ")}` : "") +
            (updated.length ? `\n  Recorded again: ${updated.join(", ")}` : "") +
            (unused.length ? `\n  Deleted ${unused.length} no lesson uses any more.` : ""),
    );
    if (!haveWebsite) {
        console.log(
            `\nNo website checkout at ${WEB_DIR}, so nothing was copied or updated.` +
                `\nSet LINK_WEB_DIR to the-link-project to fetch recordings from it.`,
        );
    }
    if (missing.length > 0) {
        console.log(
            `\nNo recording yet for:\n  ${missing.join("\n  ")}` +
                `\nThe phone's own voice reads these. Record them on the website ` +
                `(npm run record:audio in the-link-project), then run this again.`,
        );
        process.exitCode = 1;
    }
}

main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
});
